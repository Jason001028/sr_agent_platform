import { createApp, h, nextTick, reactive } from 'vue';
import { afterEach, expect, it, vi } from 'vitest';
import CoordinateInput from '../../components/CoordinateInput.vue';
let unmount = () => {};
afterEach(() => { unmount(); document.body.innerHTML = ''; vi.useRealTimers(); vi.unstubAllGlobals(); });
it('keeps empty input safe, tracks manual entry and clears it on scene changes', async () => {
  vi.useFakeTimers();
  const props = reactive({ sceneKey: 1, coordinates: null as [number, number] | null, sourceName: 'QC', batchState: 'idle' });
  const locate = vi.fn();
  const host = document.createElement('div'); document.body.append(host);
  const app = createApp(() => h(CoordinateInput, { ...props, onLocate: locate })); app.mount(host); unmount = () => app.unmount();
  const input = host.querySelector('input')!;
  expect(input.value).toBe(''); expect(input.placeholder).toBe('输入坐标 X, Y');
  expect(host.querySelector('button')!.disabled).toBe(true);
  input.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter' })); expect(locate).not.toHaveBeenCalled();
  input.value = '12,34'; input.dispatchEvent(new Event('input')); await nextTick();
  expect(host.querySelector('.coordinate-badge')!.textContent).toBe('手动');
  input.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter' })); expect(locate).toHaveBeenCalledWith('12','34');
  props.sceneKey = 2; await nextTick(); expect(input.value).toBe('');
  props.coordinates = [0, 56]; await nextTick(); expect(input.value).toBe('0,56');
  expect(host.querySelector('.coordinate-badge')!.textContent).toBe('已导入');
  await vi.advanceTimersByTimeAsync(4500); await nextTick();
  await vi.advanceTimersByTimeAsync(100); await nextTick();
  expect(host.querySelector('.coordinate-card')).toBeNull();
  props.batchState = 'done'; await nextTick(); expect(host.querySelector('.coordinate-card')).toBeNull();
  props.coordinates = [NaN, 1]; await nextTick(); expect(input.value).toBe('');
  expect(host.querySelector('.coordinate-badge')!.textContent).toBe('未提供');
});
