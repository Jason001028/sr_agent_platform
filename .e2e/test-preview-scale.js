const assert = require('node:assert/strict');
const { launchBrowser } = require('./launchBrowser');
const path = require('node:path');
(async () => {
  const browser = await launchBrowser();
  try {
    const page = await browser.newPage();
    await page.setViewport({ width: 1440, height: 900 });
    await page.goto(process.env.SR_UI_URL || 'http://127.0.0.1:4173/viewer');
    await page.waitForSelector('.psc-rail');
    const rail = await page.$('.psc-rail');
    const box = await rail.boundingBox();
    const value = () => page.$eval('.psc-rail', e => Number(e.getAttribute('aria-valuenow')));
    await rail.focus();
    await page.keyboard.press('Home');
    assert.equal(await value(), 0);
    await page.keyboard.press('ArrowLeft');
    assert.equal(await value(), 0);
    // A click is an animated jump, not a direct-manipulation teleport.
    await page.mouse.click(box.x + box.width, box.y + 14);
    assert.equal(await value(), 4);
    assert.ok(await page.$$eval('.psc-number', es => es.length) >= 2, 'old and new labels crossfade');
    const start = await page.$eval('.psc-thumb', e => e.getBoundingClientRect().x);
    await new Promise(r => setTimeout(r, 320));
    const end = await page.$eval('.psc-thumb', e => e.getBoundingClientRect().x);
    assert.ok(end - start > 10, 'thumb interpolates toward click target');
    await page.mouse.move(box.x + box.width, box.y + 14);
    await page.mouse.down();
    await page.mouse.move(box.x + box.width * .36, box.y + 14, { steps: 8 });
    assert.equal(await value(), 4, 'drag does not commit intermediate levels');
    const moving = await page.$eval('.psc-thumb', e => e.getBoundingClientRect().x);
    assert.ok(Math.abs(moving - (box.x + box.width * .36 - 8)) < 2);
    await page.mouse.up();
    assert.equal(await value(), 1, 'release snaps to closest stop');
    await new Promise(r => setTimeout(r, 320));
    assert.equal(await page.$$eval('.psc-number', es => es.length), 1);
    assert.equal(await page.$eval('.psc-number', e => e.textContent), '1/8');
    await rail.focus();
    await page.keyboard.press('End');
    await page.keyboard.press('ArrowRight');
    assert.equal(await value(), 4);
    await page.keyboard.press('Home');
    await page.mouse.move(box.x + box.width / 2, box.y + 14);
    await page.mouse.wheel({ deltaY: -100 });
    await page.waitForFunction(() => document.querySelector('.psc-rail').getAttribute('aria-valuenow') === '1');
    // Cancelled pointer interactions return to the committed level.
    await page.mouse.down();
    await page.mouse.move(box.x + box.width * .9, box.y + 14, { steps: 4 });
    await page.$eval('.psc-rail', e => e.dispatchEvent(new PointerEvent('pointercancel', { pointerId: 1 })));
    await page.mouse.up();
    assert.equal(await value(), 1);
    await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }]);
    const duration = await page.$eval('.psc-thumb', e => getComputedStyle(e).transitionDuration);
    assert.ok(parseFloat(duration.split(',')[0]) <= .001, 'reduced motion settles within 1ms');
    await page.keyboard.press('Home');
    assert.equal(await value(), 0);
    await page.keyboard.press('ArrowRight');
    await page.keyboard.press('ArrowRight');
    await new Promise(r => setTimeout(r, 30));
    await page.$eval('.psc-rail', e => e.blur());
    await page.screenshot({ path: path.join(__dirname, 'preview-scale-control.png') });
    const rect = await page.$eval('.preview-scale', e => ({ width: e.getBoundingClientRect().width, height: e.getBoundingClientRect().height }));
    assert.ok(rect.width <= 220 && rect.height <= 36);
    await page.setViewport({ width: 1280, height: 800 });
    const narrow = await page.$eval('.preview-scale', e => ({ x: e.getBoundingClientRect().x, right: e.getBoundingClientRect().right, width: e.getBoundingClientRect().width }));
    assert.ok(narrow.x >= 0 && narrow.right < 1280 && narrow.width === rect.width);
    console.log(JSON.stringify({ passed: true, rect, narrow, reducedMotion: duration, checks: ['click interpolation', 'drag follow', 'commit on release', 'nearest snap', 'label crossfade', 'keyboard boundaries', 'wheel', 'pointer cancel', 'reduced motion', '1280px layout'] }));
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
